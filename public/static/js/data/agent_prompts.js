window.buildAgentContext = function(state) {
  const { step, formula, cost, kcal, carbPct, proteinPct, fatPct, estimatedGi } = state;

  return `
- 현재 워크플로우 단계: ${step}/5 (${
  step === 1 ? "시장조사" :
  step === 2 ? "환자 프로파일링" :
  step === 3 ? "경쟁 벤치마킹" :
  step === 4 ? "배합 설계" :
  "원가 시뮬레이션"
})
- 제품: GLUCARE-M · 당뇨환자용 액상 FSMP · 200ml/팩
- 배합 요약: 이소말툴로스 ${formula?.iso || 22}g + WPI ${formula?.wpi || 10}g + MUFA ${formula?.mufa || 6}g
- 열량: ${kcal?.toFixed(0) || 200} kcal/팩
- 탄수/단백/지방 열량비: ${carbPct?.toFixed(1) || 46.8}% / ${proteinPct?.toFixed(1) || 21.2}% / ${fatPct?.toFixed(1) || 32.0}%
- 추정 GI: ${estimatedGi || 28}
- FSMP 표준제조기준: 탄수 45–50%en, 단백 18–22%en, 지방 30–38%en, GI ≤55
- 목표 MSRP: ${cost?.msrp || 45000}원, 박스당 원가 추정: ${cost?.total?.toFixed(0) || 13210}원
`.trim();
};
